    private void btnEncolar2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEncolar2ActionPerformed
               try {
            int cod = Integer.parseInt(txtCodProd.getText().trim());
            int cant = Integer.parseInt(txtCantidad.getText().trim());
            String destino = txtDestinoEntrega.getText().trim();

            Producto p = inventario.buscar(cod);
            if (p == null) {
                JOptionPane.showMessageDialog(this, "Producto no existe en el inventario.");
                return;
            }
            if (p.getStock() < cant) {
                JOptionPane.showMessageDialog(this, "Stock insuficiente. Disponible: " + p.getStock());
                return;
            }
            if (!grafo.existeCiudad(destino)) {
                JOptionPane.showMessageDialog(this, "Destino no existe en el grafo.");
                return;
            }
            if (cola.estaVacia()) {
                JOptionPane.showMessageDialog(this, "No hay camiones disponibles en la cola.");
                return;
            }

            inventario.descontarStock(cod, cant);
            Camion c = cola.desencolar();
            Entrega e = new Entrega(idEntrega++, p.getNombre(), c.getPlaca(), destino, cant);
            historial.add(e);

            JOptionPane.showMessageDialog(this,
                "Entrega registrada:\n" + e + "\nStock restante: " + p.getStock());
            txtCodProd.setText("");
            txtCantidad.setText("");
            txtDestinoEntrega.setText("");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Codigo y cantidad deben ser numericos.");
        }
    }//GEN-LAST:event_btnEncolar2ActionPerformed

